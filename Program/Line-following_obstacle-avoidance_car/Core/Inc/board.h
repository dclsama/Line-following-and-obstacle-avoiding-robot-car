/* 循迹误差权重: 中间近权重大小, 两侧远权重大 */
#define LINE_W_L    -2
#define LINE_W_ML   -1
#define LINE_W_MR   +1
#define LINE_W_R    +2

/* 循迹 PID —— 采用"非线性增益": 小误差用小增益(直线稳), 大误差用大增益(急弯猛),
 * 这样单靠一组参数无法兼顾的"直线不震荡"与"急弯跟得住"就同时满足了.
 * 注: 整体车速已按原值的 2/3 缩放 —— 转向量(增益)必须跟着一起缩,
 *     否则只降基础速度会让转向相对车速变得更猛, 手感就变了. */
#define BASE_PWM        1310  /* 基础前进速度(1540 → 1310, −15%; 避障效果比高速时好).
                                 预警减速(OBSTACLE_WARN_PCT)和避障各阶段速度都不受影响,
                                 它们用的是各自独立的参数. */
/* 赛道以平滑连续弯道为主, 误差很少跑到 |e|>=2, 所以不需要高增益去"救急弯".
 * 增益压低 + 滤波加强, 把横摆压下去; 真遇到急弯还有丢线逻辑兜底. */
/* 赛道弯曲不大, 用不到大增益; 增益越低, 车头摆动越小. */
#define LINE_KP         110   /* 小误差(|e|<=1)增益: 车速提到 1310 后出现小幅震荡, 降一档 */
#define LINE_KP_BIG     240   /* 大误差(|e|>=2)增益: 同比降, 保持非线性比例 */
#define LINE_KD         0     /* 微分系数: 置0. 数字传感器的误差只在整数间跳变,
                                 Kd 每次跳变都产生一个正负尖峰, 是左右晃动的直接来源 */

/* 误差低通滤波: 每周期向目标靠近 1/2^N.
 * 把"跳变"变成"渐变", 从源头消除 Kd/P 的激励. N越大越平滑、越迟钝. */
#define LINE_E_FILTER_SHIFT  0   /* 0=关闭误差滤波. 这一层延迟最重, 会让车迟钝/切内道 */
#define LINE_LOST_U    1270   /* 丢线时的转向量(随BASE同比降) */
/* 丢线转向量的实际上限: 只给到 BASE 的 60%, 内轮仍保留 40% 速度.
 * 这样丢线时车走的是【弧线】而不是"内轮停转原地打转" —— 后者在原地
 * 转圈找线, 看起来像车坏了, 也不会扩大搜索范围. */
#define LINE_LOST_U_MAX  (BASE_PWM * 60 / 100)

/* 转向量上限: 取 BASE_PWM 时, 内轮最多减速到 0(停住), 不会反转.
 * 反转会让车身猛地甩出去 —— 这是"震荡 + 甩到丢线"的主要来源, 限住它.
 * 想更猛(急弯更跟得住)就调大, 想更温和就调小. */
#define LINE_U_MAX      BASE_PWM   /* 回退: 内轮最多停住, 不再额外限制 */

/* 转向量斜率限制: 每周期(10ms)u 最多变化多少.
 * 数字传感器的误差是离散跳变的, PID 输出会跟着一跳一跳, 车就左右晃.
 * 限制变化速率相当于给执行器加惯性 —— 抑制晃动, 又不牺牲稳态精度.
 * 调小=更稳但反应更慢; 调大=反应快但更容易晃. */
#define LINE_U_SLEW     100   /* 小误差(|e|<=1)时的变化率上限: 收紧, 压住线上小幅甩动 */
#define LINE_U_SLEW_BIG 300   /* 大误差(|e|>=2)时放宽: 真弯道要跟得上 */

/* 避障结束后、还没重新压上线时用的"找线舵量".
 * 这一段如果用满舵(LINE_LOST_U, 限幅后 900 = 内轮停转), 会以很大角度冲过线,
 * 循迹接管后又要反过来猛修, 看起来就是"回线太急、接不稳".
 * 用 650 画弧切回去, 压上线后立即恢复满舵权限. */
#define AVOID_SEARCH_U   650

/* 上电延时(ms), 给你放车、退开的时间 */
#define STARTUP_DELAY_MS  2000

/* 横线检测: 全黑连续 N 次认定横线(去抖).
 * 起跑线和终点线都是长黑线, 所以不能"第一次全黑就停":
 *   第 1 次全黑 = 起跑线(忽略, 继续循迹)
 *   第 2 次全黑 = 终点线(停车) */
#define BLACK_DEBOUNCE      4     /* 持续确认次数: 配合下面的"2路"放宽, 防止直角弯误判 */

/* 用【里程】区分起跑线和终点线, 比"数第几次横线"更稳:
 * 起跑线在起点附近(里程≈0), 只有跑过一段距离后遇到的横线才可能是终点线.
 * 这样即使起跑线没被识别到、或者车根本没经过起跑线, 也不会漏掉终点. */
#define FINISH_MIN_TRAVEL_CM   100
/* 判定"横线"所需的最少压线路数.
 * 终点线前是左转弯, 车头是斜的, 4 路不会同时压到横线, 通常只有 3 路 ——
 * 所以不能要求"4 路全黑", 否则会漏检、把终点线当成普通弯道.
 * 直角弯的黑线是依次经过各路传感器的, 不会多路同时持续压线, 因此 3 路仍能区分. */
/* 判定"横线"的最少压线路数.
 * 终点前是【大左转弯接横向终点线】, 车头斜着压线时往往只有 2 路, 所以放到 2;
 * 但必须"中间两路至少一路压线"(见 check_finish_line), 否则直角弯会误判. */
#define LINE_BLACK_LINE_MIN 2

/* 编码器计数 -> 厘米 换算.
 * 实测: 直行段 100 计数走了约 6.5cm  ->  约 15 计数/cm.
 * 影响 FINISH_MIN_TRAVEL(起终点里程门槛) 与 FINISH_EXTRA(越线距离). */
#define ENCODER_CNT_PER_CM   15

/* 越线停车: 检测到终点线后只再走一点点就停.
 * 规则要求"车尾投影不越过终点线", 所以不能走满车长(12cm), 否则车尾会过线. */
#define FINISH_EXTRA_CM      3
#define FINISH_EXTRA_CNT     (FINISH_EXTRA_CM * ENCODER_CNT_PER_CM)
#define FINISH_MIN_TRAVEL_CNT (FINISH_MIN_TRAVEL_CM * ENCODER_CNT_PER_CM)
#define FINISH_PWM           1000    /* 越线前进速度(原1500的2/3, 慢速直行便于停准) */

/* 超声波 */
/* 回波超时. 原来是 10ms —— 而 measure() 里有两个等待循环, 无回波时
 * 单次测量最长会阻塞 20ms, 把 10ms 的控制周期拉长到 20~30ms,
 * 控制器"看不清"车的位置, 形成极限环(车头持续左右摆).
 * 降到 3ms: 覆盖约 51cm(避障只需 30cm 内), 最长阻塞 6ms, 控制在周期内. */
/* 回波超时. 恢复成 3000us —— 2000us 对某些模块"等回波上升沿"可能太短,
 * 会让五个通道全部读成无回波. 3000us 覆盖约 51cm. */
#define US_TIMEOUT_US         3000

/* 测量有效性窗口: 落在这个区间外的读数一律按"无回波(999)"处理.
 *  · < 盲区(约2cm): HC-SR04 盲区内收不到回波, 量到的短脉冲都是干扰
 *  · > 50cm: 超时截断, 或者 ECHO 被外部上拉悬空成高电平
 *            (PA12 是蓝板 USB D+, 带 1.5k 上拉) */
#define US_BLIND_CM           3
#define US_MAX_VALID_CM       50
/* 回波保持时间(ms): 某一路突然丢掉回波时, 短暂沿用上一次有效读数.
 * 斜角障碍常常"越靠近越测不到", 这层能把接近过程中的丢包补上.
 * 必须短于撞上判定所需的连续时间(US_COLLISION 的 200ms), 否则会把
 * "障碍刚离开视野"误判成"顶上了". */
#define US_HOLD_MS            150
/* 前方/斜前触发绕障的距离(cm).
 * 注意 HC-SR04 有约 2cm 盲区: 障碍贴到传感器上反而测不到(输出无回波),
 * 所以阈值不能贴着盲区设, 要留出余量, 让车在障碍逼近盲区之前就触发.
 * 代价是设太大容易把路过的远处障碍也当成需要绕行的目标. */
/* 触发距离改回偏近的一档:
 * 障碍摆在赛道旁边, 传感器斜着装, 20/24cm 会把"根本碰不到"的路边障碍也拉进来,
 * 车被迫绕出去、然后丢线. 15/18cm 只对真正压在行进路径上的障碍反应. */
/* 触发/预警距离: 车速已回到 1310, 用回低速时验证过的这一档.
 * 阈值放太远会把赛道旁"碰不到"的障碍也拉进来(31cm 档位踩过这个坑). */
#define OBSTACLE_DIST_CM      28      /* 正前触发距离(cm): 正前垂直安装, 不易被路边障碍误触发,
                                         放远一点用来接住斜前漏掉的障碍 */
#define OBSTACLE_DIST_R_CM    26      /* 右前触发距离(cm): 与左前对称 */

/* ---- 撞上障碍物 -> 直接顶开 ----
 * 前向传感器【持续】读到极近距离, 就认为车已经顶到障碍物上了(绕不过去).
 * 规则允许把障碍物撞开再继续循迹, 可以拿部分分数, 比卡死或乱绕强.
 *
 * 注意: HC-SR04 有约 2cm 盲区, 真的贴死反而测不到(变成无回波).
 * 所以阈值放在盲区之外, 在"快贴上"的时候就判定, 抢在卡死之前顶开. */
#define US_COLLISION_CM        10     /* 小于这个距离认为顶上了 */
#define COLLISION_CONFIRM_MS   200    /* 需要持续这么久(防止误判) */

/* ---- 编码器堵转检测(超声波的兜底) ----
 * 障碍物摆放角度刁钻时, 声束会被反射到别的方向, 读数变成"无回波",
 * 无论阈值调多宽都看不见. 这里改用编码器: 只要 PWM 不低、车却在窗口内
 * 几乎不动, 就判定被顶住, 直接交给顶开逻辑.
 * 只对"轮子真的不转"有效; 轮子打滑空转的情况它看不出来. */
#define STALL_WINDOW_MS        500    /* 检测窗口(ms) */
#define STALL_MIN_CNT          25     /* 窗口内平均里程计数低于这个就算堵转(≈1.7cm) */
#define STALL_MIN_PWM          800    /* 基础车速低于这个值时不判(起步/减速阶段) */
#define PUSH_PWM               1600   /* 顶开时的推力(两轮同速前进): 加大以便真的把障碍顶开 */
#define PUSH_MAX_MS            1500   /* 顶开阶段最长时间 */
#define PUSH_CLEAR_MS          300    /* 至少顶这么久, 且前向已让开才恢复循迹 */

/* 左右前距离差超过这个值, 才认为"障碍在哪一侧"是明确的.
 * 差距很小时不投票, 改用两侧净空决定 —— 否则两个斜装传感器的安装偏差
 * 或单侧干扰就会把方向判反(右前方的障碍被当成左侧, 于是往右绕撞上去). */
#define OBSTACLE_SIDE_MARGIN_CM  6
/* 左前触发距离. 左前是斜装的, 测得的是【斜向】距离:
 * 20cm 斜距换算成正前方只有约 14cm, 所以实际感觉"贴脸才触发".
 * 26cm 斜距 ≈ 正前方 18cm, 给避障留出动作时间. */
#define OBSTACLE_DIST_L_CM    26      /* 与右前一致(左前误触发已由 ECHO 空闲电平检查解决) */

/* 避障(状态机绕行). 赛道障碍基本出现在【侧前方】, 据此组织判断:
 *   触发 : 左前/右前的斜装传感器(不是侧向的)
 *   转回 : 【侧向】传感器确认旁边安全了 -> 可以绕回巡线
 *   全程降速
 * 用侧向传感器判断"能不能绕回"是有道理的: 车一旦开始转向, 斜前传感器的
 * 朝向也跟着转, 它的"距离变大"并不代表真的让开了; 而侧向传感器测的是垂直
 * 方向的净空, 更接近"横向有没有东西挡着". */
/* 障碍确认: 窗口内【累计命中】, 而不是"连续命中".
 * 斜角摆放的障碍回波时有时无, 连续判据中间丢一拍就清零, 永远确认不了.
 * 每 10ms 一拍:
 *   16 拍(160ms)窗口内累计命中 8 拍(80ms) -> 确认.
 * 稳态全部命中时 80ms 就触发, 和原来差不多; 丢一半回波时仍能在 160ms 内确认.
 * 单次毛刺只贡献 1~2 拍, 远不够 8 拍. */
#define OBSTACLE_WINDOW_CYCLES 16
#define OBSTACLE_WINDOW_HITS   8

/* ---- 近距带: 稍远处的斜面障碍 ----
 * 障碍如果是个斜面/摆放角度刁钻, 车靠近时读数可能一直卡在触发阈值【外侧】,
 * 始终不肯越过阈值, 但"持续存在"本身就是很强的证据.
 * 落在 [触发距离, 触发距离 + 余量] 之间算一个"近点":
 * 单拍和其他瞬时噪声一样不计较, 但只要持续 OBSTACLE_NEAR_HITS 拍(约 500ms),
 * 就延时触发避障 —— 反应慢一点, 但不会漏掉这种目标.
 * 代价: 赛道旁持续存在的墙/挡板也可能被当成障碍. 误触发多就减小余量或加长拍数. */
#define OBSTACLE_NEAR_MARGIN_CM  8
#define OBSTACLE_NEAR_HITS       50   /* 10ms/拍 -> 约 500ms 持续存在 */

/* 绕障结束后的静默期(ms): 这段时间内【任何一侧】都不允许再触发绕障.
 *
 * 原来的冷却只忽略【同一侧】:
 *     (冷却已过 || 这一侧和上次不同)
 * 于是"刚绕完右侧障碍"之后, 只要左侧出现一次干扰(左前 ECHO 接在 PA12,
 * 是蓝板 USB D+, 本来就容易受扰), 就会判成"左侧新障碍", 冷却被绕过,
 * 立刻又启动一次绕障 —— 看起来就像"绕障途中突然又绕了一次".
 * 注意: 状态机本身不会在 AVOID 里再触发避障(检测只在 FOLLOW 里调用),
 * 所以这种连发一定发生在"交还循迹之后"。 */
#define AVOID_SETTLE_MS       800

/* 一次绕障流程的结束条件: 车重新回到线上.
 * 在回到线上之前不再接受新避障 —— 并线时车头扫到路边"本来碰不到"的障碍,
 * 否则会莫名其妙再绕一次. 下面是兜底期限: 一直找不到线也不会永久失明. */
#define AVOID_REJOIN_TIMEOUT_MS  3000

/* 绕障期间 + 交还后这段时间内, 暂停终点线检测(ms).
 * 原因: 车斜着绕回黑线时, 车身与线几乎垂直, 好几路传感器会同时压线 ——
 * 正好符合"3 路以上同时压线 = 横线"的终点判据, 于是误停车.
 * 绕障前后本来就不可能是终点, 屏蔽掉没有副作用. */
#define FINISH_GUARD_MS       800

/* 预警减速: 障碍进入预警区就先降速(但不避障), 给真正的避障动作留出时间和距离.
 * 转向量会按同样的百分比缩放, 保证轨迹形状不变, 只是整体变慢. */
/* 绕障冷却: 刚绕过障碍后的一小段时间内, 忽略【同一侧】的障碍.
 * 防止"刚绕过的那一个障碍"被再次当成新障碍, 导致交还循迹后立刻又绕一次.
 * 另一侧的新障碍不受这个限制. */
#define AVOID_COOLDOWN_MS     1200    /* 冷却时长(ms): 只挡【同一侧】.
                                         原来是 2500, 障碍摆得密时会把真正的新障碍
                                         一起挡掉, 表现为"怎么都不触发" */

/* 避障每个子阶段的最长时间(ms). 防止编码器断线/车轮堵转时 turn_diff、
 * avg_abs_travel 不再变化, 状态机永远卡在某个子阶段里(电机会一直顶着). */
/* 每个子阶段的兜底超时. 注意它同时是"斜出距离的实际上限":
 * 如果 3.5s 内走不完命令的计数, 状态机会提前切段, 表现就是"斜出距离加了
 * 却没效果". 放到 6s, 保证 1400 计数(约 90cm)能真的走完. */
#define AV_STAGE_TIMEOUT_MS   6000

#define OBSTACLE_WARN_CM      33      /* 预警距离(cm): 必须大于触发距离(26) */
#define OBSTACLE_WARN_PCT     75      /* 预警时的车速百分比(%); BASE降了, 比例要抬高,
                                         否则减完只剩7.5%占空比, 电机可能推不动 */

/* 绕行速度. 注意: 转弯半径 R = (轮距/2)×(vL+vR)/(vR-vL),
 * 分子是"和"(基础速度), 分母是"差"(差速). 想只提速不改半径, 两者必须同比例调. */
/* ---- 原地转向(停车打转) ----
 * 左右轮反向同速, 车绕着两轮中点旋转, 不产生前向位移.
 * 横向让开完全由"转出去 -> 直行 -> 转回来"里的直行段产生. */
#define AV_PIVOT_PWM          1200    /* 原地转向的轮速 */
/* ---- 梯形绕障: 斜出 -> 平行 -> 斜回 ----
 *
 *               障碍
 *         ┌────────────┐
 *        ╱              ╲
 * ──────╱                ╲──────  黑线
 *
 * 三段直行 + 三次原地转向:
 *   ① 原地转 θ         车头斜指赛道外侧 (AV_TURN_MAX_DIFF)
 *   ② 斜出段 L1        边走边让开, 横移 = L1 × sinθ
 *   ③ 原地反向转       角度独立, 通常略小于① (AV_TURN_PAR_DIFF)
 *   ④ 平行段 L2        车身与黑线平行地从障碍旁边通过
 *   ⑤ 原地转向黑线     角度可独立设置(通常比转出角小)
 *   ⑥ 直行找线         压到黑线后交还循迹
 *
 * 与旧"转出->直行->转回"相比, 多了 ③④ 两段: 通过障碍时车身是【平行】的,
 * 轮胎到障碍的横向余量就是 L1 × sinθ, 不用边转边蹭. */

/* 转出(①)的角度. 标定(原地转向): 实测 350 计数 ≈ 70°, 即 ≈5 计数/度.
 * 300 / 5 = 60° (原 250 = 50°, 实测起步让开不够). */
#define AV_TURN_MAX_DIFF      300

/* 转回(③)的角度. 不必和转出角相等: 赛道本身是曲线, "与黑线平行"只是个
 * 理想参考. 转回角小一点, 车身在平行段会略朝外侧(约 10°), 还能继续攒一点
 * 横向余量; 之后 ⑤ 再把车头拉回黑线方向.
 * 250 / 5 = 50° (比转出角小 10°). */
#define AV_TURN_PAR_DIFF      250

/* 转回黑线(⑤)的角度, 和上面解耦: 这一下决定"以多大角度压回黑线".
 * 30° -> 40° 后仍然"长时间找不到线, 触发丢线打转", 说明斜插角度还是太缓:
 * 横移固定时, 压回黑线要走的距离 = 横移 / tan(本角度), 角度越小这段越长.
 * 250/5 = 50°, 回线距离比 40° 时缩短约 30%. */
#define AV_TURN_IN_DIFF       250

/* 斜出段距离. 横移 = 本段 × sinθ.
 * 注意: 实测横移比按 15 计数/cm 推算的明显偏小, 所以这里不再按厘米标定,
 * 直接以"实测值"为准往上加. */
#define AV_SLANT_OUT_CNT      1400    /* 1100 -> 1400 (+27%); 配合 6s 阶段超时才能真正走完 */

/* 平行段距离: 车身与黑线平行通过障碍的长度.
 * 横向已经让开很多, 这一段只需要把车身带过去, 不需要太长. */
#define AV_PARALLEL_CNT       80      /* 40 -> 80, 平行通过段再长一点 */

/* 直行段速度. 必须高过电机低速死区: 950 时实测右轮(100%增益)不转、
 * 左轮(105%)在转, 车变成绕着右轮原地打转 —— 表现为"直行距离几乎为0,
 * 但车转了一大圈". 1150 与原地转向同档, 两轮都能稳定起步. */
#define AV_PASS_PWM           1150
#define AV_PASS_DIFF          0

/* 找线速度: 同样要高于低速死区 */
#define AV_SEARCH_PWM         1050
/* 找线最长时间(兜底). 转回角度变小后, 斜着回线要走更长的路, 给足时间,
 * 否则还没压到线就超时交给循迹, 会进入丢线打转. */
#define AV_SEARCH_TIMEOUT_MS  4500

/* ---- 找线阶段的追加机制 ----
 * 直行找线 AV_SEARCH_RETRY_MS 还没压到线, 说明前面的横移/角度估算有偏差
 * (赛道是曲线也会造成这种情况). 这时朝黑线方向再转一个不大的角度, 然后
 * 继续直行找线 —— 相当于给自己补一次机会. 只追加一次. */
#define AV_SEARCH_RETRY_MS    2000
#define AV_SEARCH_RETRY_DIFF  150     /* 150 / 5 = 30° */

/* 控制周期(ms) */
#define LOOP_MS             10

